/** Пиллы над инпутом — ультра-короткие подписи */
export const GUIDE_QUICK_PILLS: { id: string; label: string }[] =
  APP_KNOWLEDGE.map((e) => ({ id: e.id, label: e.pill }));

function normalize(text: string) {
  return text
    .toLowerCase()
    .replaceAll("ё", "е")
    .replace(/[?»«!]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** Точный или близкий поиск ответа в базе знаний */
export function lookupKnowledge(userText: string): string | null {
  const n = normalize(userText);
  if (!n) return null;

  for (const entry of APP_KNOWLEDGE) {
    const q = normalize(entry.question);
    const p = normalize(entry.pill);
    if (n === q || n === p) return entry.answer;
    if (n.includes(q) || q.includes(n) || n.includes(p) || p.includes(n)) {
      // avoid tiny accidental matches
      if (n.length >= 8 || p.length <= n.length + 2) return entry.answer;
    }
  }

  // Soft aliases for pill variants
  const aliases: { keys: string[]; id: string }[] = [
    { keys: ["как это работает", "как работает"], id: "how-works" },
    { keys: ["до скольки", "до 21", "дедлайн"], id: "deadline" },
    { keys: ["опоздал", "после 21"], id: "missed-deadline" },
    { keys: ["на неделю", "неделю вперед", "неделю вперёд"], id: "week-ahead" },
    { keys: ["отмен"], id: "cancel" },
    { keys: ["ребен", "ребён", "детск", "ребенку", "ребёнку"], id: "kids" },
    { keys: ["без сахар"], id: "no-sugar" },
    { keys: ["кбжу", "бжу", "калор"], id: "kbju" },
    { keys: ["флэт", "флет"], id: "flat-croissant" },
    { keys: ["без орех", "орех"], id: "no-nuts" },
    { keys: ["тепл", "тёпл", "горяч"], id: "warm" },
    { keys: ["тих", "пуш"], id: "silent-push" },
    { keys: ["стоит достав", "цена достав", "сколько достав", "цена доставки"], id: "delivery-price" },
    { keys: ["ручк двери", "на ручке", "у двери"], id: "door-handle" },
    { keys: ["остыл"], id: "got-cold" },
    { keys: ["соседск", "шеринг"], id: "neighbor-share" },
    { keys: ["+50", "50 бонус", "получить +50", "как получить"], id: "plus-50" },
    {
      keys: ["оплатить бонус", "оплата бонус", "бонусами", "списать бонус"],
      id: "pay-bonuses",
    },
    { keys: ["кофе за", "бесплатный кофе", "кофе за балл"], id: "free-coffee" },
    { keys: ["подарок", "другу"], id: "gift-friend" },
  ];

  for (const a of aliases) {
    if (a.keys.some((k) => n.includes(k))) {
      const entry = APP_KNOWLEDGE.find((e) => e.id === a.id);
      if (entry) return entry.answer;
    }
  }

  return null;
}
